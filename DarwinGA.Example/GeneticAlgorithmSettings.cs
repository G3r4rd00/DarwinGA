using Microsoft.Extensions.Configuration;
using System.Globalization;

namespace DarwinGA.Example
{
    internal sealed class GeneticAlgorithmSettings
    {
        public double MutationProbability { get; init; } = 0.1;

        

        public bool EnableAdaptiveRates { get; init; } = false;

        public int PopulationSize { get; init; } = 50;

        // Number of best individuals carried unchanged into the next generation (0 = no reinsertion).
        public int ReinsertCount { get; init; } = 0;

        // Maximum number of generations before stopping (the run also stops when the optimum is found).
        public int MaxGenerations { get; init; } = 100;

        // Number of individuals of the initial population generated by AI (the rest are random).
        public int AIInitialPopulationCount { get; init; } = 3;

        // Fraction of each new generation produced by the AI crossover (the rest uses the classic crossover).
        public double AICrossoverRatio { get; init; } = 0.1;

        // Number of offspring the AI crossover generates per generation.
        public int AICrossoverCount => AICrossoverRatio > 0
            ? Math.Clamp((int)Math.Round(PopulationSize * AICrossoverRatio), 1, PopulationSize)
            : 0;

        public static GeneticAlgorithmSettings FromConfiguration(IConfiguration configuration)
        {
            if (configuration is null)
                throw new ArgumentNullException(nameof(configuration));

            var mutationRaw = configuration["GeneticAlgorithm:MutationProbability"];
            var mutationProbability = double.TryParse(mutationRaw, NumberStyles.Float, CultureInfo.InvariantCulture, out var parsedMutation)
                ? parsedMutation
                : 0.1;
            mutationProbability = Math.Clamp(mutationProbability, 0.0, 1.0);

            var adaptiveRatesRaw = configuration["GeneticAlgorithm:EnableAdaptiveRates"];
            var enableAdaptiveRates = bool.TryParse(adaptiveRatesRaw, out var parsedAdaptiveRates)
                ? parsedAdaptiveRates
                : false;

            

            var populationRaw = configuration["GeneticAlgorithm:PopulationSize"];
            var populationSize = int.TryParse(populationRaw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedPopulation)
                ? parsedPopulation
                : 0;

            if (populationSize <= 0)
                throw new ArgumentException("Population size must be a positive integer.", nameof(configuration));

            var reinsertRaw = configuration["GeneticAlgorithm:ReinsertCount"];
            var reinsertCount = int.TryParse(reinsertRaw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedReinsert)
                ? Math.Clamp(parsedReinsert, 0, populationSize)
                : 0;

            var maxGenerationsRaw = configuration["GeneticAlgorithm:MaxGenerations"];
            var maxGenerations = int.TryParse(maxGenerationsRaw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedMaxGenerations) && parsedMaxGenerations > 0
                ? parsedMaxGenerations
                : 100;

            var aiInitialRaw = configuration["GeneticAlgorithm:AIInitialPopulationCount"];
            var aiInitialPopulationCount = int.TryParse(aiInitialRaw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedAiInitial)
                ? Math.Clamp(parsedAiInitial, 0, populationSize)
                : Math.Min(3, populationSize);

            var aiCrossoverRaw = configuration["GeneticAlgorithm:AICrossoverRatio"];
            var aiCrossoverRatio = double.TryParse(aiCrossoverRaw, NumberStyles.Float, CultureInfo.InvariantCulture, out var parsedAiCrossover)
                ? Math.Clamp(parsedAiCrossover, 0.0, 1.0)
                : 0.1;

            return new GeneticAlgorithmSettings
            {
                MutationProbability = mutationProbability,
                EnableAdaptiveRates = enableAdaptiveRates,
                PopulationSize = populationSize,
                ReinsertCount = reinsertCount,
                MaxGenerations = maxGenerations,
                AIInitialPopulationCount = aiInitialPopulationCount,
                AICrossoverRatio = aiCrossoverRatio
            };
        }
    }
}