using DarwinGA.AI;
using DarwinGA.Interfaces;
using System;
using System.Collections.Generic;
using System.Linq;

namespace DarwinGA.Evolutionals.BinaryEvolutional.Crossers
{
    /// <summary>
    /// AI-based population crossover operator.
    /// Serializes the selected parents, sends them to an AI service (e.g., ChatGPT)
    /// and receives up to <c>offspringCount</c> children back.
    /// The genetic algorithm fills the rest of the population with its classic <see cref="ICross{T}"/>.
    /// </summary>
    public class AICrosser : IPopulationCrosser<BinaryEvolutional>
    {
        private readonly IAIProvider _aiProvider;
        private readonly int _offspringCount;
        private readonly string _systemMessage;
        private readonly Func<List<BinaryEvolutional>,string> SerializePopulation;
        private readonly Func<string, List<BinaryEvolutional>> DeserializePopulation;


        /// <summary>
        /// Creates a new AI-based crossover operator.
        /// </summary>
        /// <param name="aiProvider">The AI provider to use for crossover operations.</param>
        /// <param name="offspringCount">Maximum number of offspring generated by the AI per generation (0 disables the AI call).</param>
        /// <param name="serializePopulation">Function used to serialize parents before sending them to the AI.</param>
        /// <param name="deserializePopulation">Function used to deserialize AI response into offspring.</param>
        /// <param name="systemMessage">System message sent with every crossover request.</param>
        public AICrosser(
            IAIProvider aiProvider,
            int offspringCount,
            Func<List<BinaryEvolutional>, string> serializePopulation,
            Func<string, List<BinaryEvolutional>> deserializePopulation,
            string systemMessage)
        {
            if (offspringCount < 0)
                throw new ArgumentOutOfRangeException(nameof(offspringCount), "Offspring count cannot be negative.");

            _aiProvider = aiProvider ?? throw new ArgumentNullException(nameof(aiProvider));
            _offspringCount = offspringCount;
            SerializePopulation = serializePopulation ?? throw new ArgumentNullException(nameof(serializePopulation));
            DeserializePopulation = deserializePopulation ?? throw new ArgumentNullException(nameof(deserializePopulation));
            _systemMessage = systemMessage ?? throw new ArgumentNullException(nameof(systemMessage));
        }

        public List<BinaryEvolutional> CrossPopulation(List<BinaryEvolutional> parents)
        {
            if (_offspringCount == 0 || parents == null || parents.Count == 0)
                return new List<BinaryEvolutional>();

            // 1. Serializar la población a JSON
            string serializedParents = SerializePopulation(parents);

            // 2. Enviar a la IA, recibir respuesta y deserializarla
            try
            {
                // The provider may be shared (e.g. with the initial population creator), so set our system message on every call.
                _aiProvider.SetSystemMessage(_systemMessage);

                // La llamada es asíncrona, pero la interfaz es síncrona
                string aiResponse = _aiProvider.SendPromptAsync(serializedParents).GetAwaiter().GetResult();
                return DeserializePopulation(aiResponse).Take(_offspringCount).ToList();
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Error calling AI service: {ex.Message}");
                // En caso de error no devolvemos hijos: el algoritmo completa la población con el cruce clásico
                return new List<BinaryEvolutional>();
            }
        }
    }
}
